local H = require 'tests.helpers'
local base = require 'ipr.base'
local ctx_mod = require 'ipr.ctx'
local config = require 'ipr.config'

local function resolve(dir)
  return base.resolve(assert(ctx_mod.repo_info(dir)))
end

describe('base resolution', function()
  before_each(function()
    config.setup {}
  end)

  it('falls back to the default branch for a branch off main', function()
    local dir = H.repo()
    H.git(dir, 'switch', '-q', '-c', 'feature')
    H.write(dir, 'a.txt', 'a\n')
    H.commit(dir, 'a')
    assert.same({ ref = 'main', source = 'ancestor' }, resolve(dir))
  end)

  it('picks the nearest local ancestor branch for untracked stacks', function()
    local dir = H.repo()
    H.git(dir, 'switch', '-q', '-c', 'layer-1')
    H.write(dir, 'a.txt', 'a\n')
    H.commit(dir, 'a')
    H.git(dir, 'switch', '-q', '-c', 'layer-2')
    H.write(dir, 'b.txt', 'b\n')
    H.commit(dir, 'b')
    assert.same({ ref = 'layer-1', source = 'ancestor' }, resolve(dir))
  end)

  it('ignores other branches pointing at HEAD', function()
    local dir = H.repo()
    H.git(dir, 'switch', '-q', '-c', 'feature')
    H.write(dir, 'a.txt', 'a\n')
    H.commit(dir, 'a')
    H.git(dir, 'branch', 'feature-copy')
    assert.same({ ref = 'main', source = 'ancestor' }, resolve(dir))
  end)

  it('uses the dt parent from git config', function()
    local dir = H.repo()
    H.git(dir, 'branch', 'parent')
    H.git(dir, 'switch', '-q', '-c', 'child')
    H.git(dir, 'config', 'branch.child.wgh-parent', 'parent')
    assert.same({ ref = 'parent', source = 'dt' }, resolve(dir))
  end)

  it('uses the gh stack parent', function()
    local dir = H.repo()
    H.git(dir, 'branch', 'one')
    H.git(dir, 'switch', '-q', '-c', 'two')
    H.write(
      dir,
      '.git/gh-stack',
      vim.json.encode { stacks = { { trunk = { branch = 'main' }, branches = { { branch = 'one' }, { branch = 'two' } } } } }
    )
    assert.same({ ref = 'one', source = 'gh_stack' }, resolve(dir))
  end)

  it('prefers a saved override over everything else', function()
    local dir = H.repo()
    H.git(dir, 'branch', 'other')
    H.git(dir, 'switch', '-q', '-c', 'feature')
    H.git(dir, 'config', 'branch.feature.wgh-parent', 'main')
    local info = assert(ctx_mod.repo_info(dir))
    assert.is_true(base.set_override(info, 'other'))
    assert.same({ ref = 'other', source = 'override' }, resolve(dir))
    base.clear_override(info)
    assert.same({ ref = 'main', source = 'dt' }, resolve(dir))
  end)

  it('rejects overrides that are not refs', function()
    local dir = H.repo()
    H.git(dir, 'switch', '-q', '-c', 'feature')
    local ok, err = base.set_override(assert(ctx_mod.repo_info(dir)), 'nope')
    assert.is_false(ok)
    assert.matches('not a valid ref', err)
  end)

  it('skips a resolver result that no longer exists', function()
    local dir = H.repo()
    H.git(dir, 'switch', '-q', '-c', 'feature')
    H.write(dir, 'a.txt', 'a\n')
    H.commit(dir, 'a')
    H.git(dir, 'config', 'branch.feature.wgh-parent', 'deleted-branch')
    assert.same({ ref = 'main', source = 'ancestor' }, resolve(dir))
  end)

  it('prefers origin/<ref> when the local branch is stale', function()
    local upstream = H.repo()
    local dir = vim.fn.tempname()
    H.git(vim.fn.getcwd(), 'clone', '-q', upstream, dir)
    H.write(upstream, 'u.txt', 'u\n')
    H.commit(upstream, 'upstream moved')
    H.git(dir, 'fetch', '-q')
    H.git(dir, 'switch', '-q', '-c', 'feature', 'origin/main')
    H.write(dir, 'a.txt', 'a\n')
    H.commit(dir, 'a')
    H.git(dir, 'config', 'branch.feature.wgh-parent', 'main')
    assert.same({ ref = 'origin/main', source = 'dt' }, resolve(dir))
  end)
end)

describe('ctx.build', function()
  it('builds a ctx with merge base and repo name', function()
    local dir = H.repo()
    local main_sha = H.git(dir, 'rev-parse', 'HEAD')
    H.git(dir, 'switch', '-q', '-c', 'feature')
    H.write(dir, 'a.txt', 'a\n')
    H.commit(dir, 'a')
    local ctx = assert(ctx_mod.build(dir))
    assert.equals(dir, ctx.root)
    assert.equals('feature', ctx.branch)
    assert.equals(main_sha, ctx.merge_base)
    assert.equals(vim.fs.basename(dir), ctx.repo)
  end)

  it('errors outside a git repo', function()
    local dir = vim.fn.tempname()
    vim.fn.mkdir(dir, 'p')
    local ctx, err = ctx_mod.build(dir)
    assert.is_nil(ctx)
    assert.equals('not in a git repository', err)
  end)
end)
